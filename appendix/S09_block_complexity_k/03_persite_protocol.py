"""Per-site comparison of k with the raw morphological indicators (SI Table S6).

Manuscript items
* SI Table S6: mean and s.d. across the ten sites of test accuracy and AUC for
  three feature sets (rows): block complexity k alone, PC1 + PC2 of the raw 25
  indicators (a two-component PCA of the raw 25 indicators) and the raw 25
  indicators.
* SI S9 (comparison of classification quality) and the mean per-site AUC of k
  and of the 25 indicators quoted in the Discussion.

Protocol (config.yaml ``block_complexity.persite``, ``block_complexity.classifier``,
``pca.raw_benchmark``)
* Evaluation subset: the buildings of each site with a valid k, complete
  Tree-SHAP attributions and all 25 raw indicators (k_common.evaluation_subset).
* 80/20 train/test split stratified by label, random seed 42.
* XGBoost with 200 trees, max depth 6, learning rate 0.1, random seed 42
  (``block_complexity.classifier``, the classifier of the SI S9 comparison,
  not the main per-site model of Methods 4.4); one model per site and
  feature set; favela = class 1; intercept = favela share of the training
  rows (``base_score: training_label_mean``); predicted class = P(favela) > 0.5.
* PC1 + PC2 of the raw 25 indicators: a two-component PCA (seed 42) of the
  unstandardised 25 raw indicators, fitted within each site on its whole
  evaluation subset.
* Summary: mean and population s.d. (ddof 0) across the sites of the per-site
  values rounded to three decimals.

Inputs
* outputs/appendix/S09_block_complexity_k/block_complexity_k.csv (02)
* products.features_gpkg (main/01_features), products.shap_gpkg (main/02_classification)

Outputs (outputs/appendix/S09_block_complexity_k/)
* k_persite_metrics.csv       per site: evaluation-subset size, n train / test,
                              accuracy and AUC of each feature set
* k_persite_summary.csv       mean, s.d., min, max across the sites (SI Table S6)
* table_bettencourt_persite.tex   SI Table S6 in LaTeX

Run (from the repository root), after 02_block_complexity_k.py:
    python appendix/S09_block_complexity_k/03_persite_protocol.py
"""
from __future__ import annotations

import numpy as np
import pandas as pd
from sklearn.decomposition import PCA
from sklearn.metrics import accuracy_score, roc_auc_score
from sklearn.model_selection import train_test_split

from favela_xai.config import load_config
from favela_xai.io import write_table, write_text
from favela_xai.model import fit_classifier
from k_common import RAW, evaluation_subset, read_k, site_table, tex_number

# feature set -> (row label of SI Table S6, number of features)
FEATURE_SETS = {
    "k": ("Block complexity $k$ alone", 1),
    "feature_basic": ("PC1 + PC2 of the raw 25 indicators", 2),
    "morph25": ("Raw 25 indicators", 25),
}


def table_tex(summary: pd.DataFrame, cfg) -> str:
    """SI Table S6 in LaTeX (caption values from config.yaml)."""
    m = cfg.section("block_complexity.classifier")
    ps = cfg.section("block_complexity")["persite"]
    test_pct = int(round(100 * float(ps["test_size"])))
    lines = [
        "% Supplementary Table S6. Generated by appendix/S09_block_complexity_k/03_persite_protocol.py",
        r"\begin{table}[H]",
        r"\centering",
        rf"\caption{{Per-site classification metrics under {100 - test_pct}/{test_pct} train/test",
        rf"  split per site (XGBoost, {m['n_estimators']} trees, max depth {m['max_depth']}, learning rate",
        rf"  {tex_number(m['learning_rate'], None)}, random seed {m['random_state']}), mean across the ten",
        r"  sites. ``Block complexity $k$'' is the unsupervised",
        r"  single-metric framework as originally",
        r"  proposed\citep{bettencourt2025infrastructure}; the remaining",
        r"  feature sets are derived from the 25 momepy morphological",
        r"  indicators computed in this study. ``PC1 + PC2'' is a two-component PCA of the 25 raw indicators,"
        "\n"
        r"  fitted within each site without standardising them.}",
        r"\label{tab:bettencourt_persite}",
        r"\small",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Feature set & $n_{\text{features}}$ & Acc (mean) & Acc (sd) &",
        r"AUC (mean) & AUC (sd) \\",
        r"\midrule",
    ]
    for r in summary.itertuples():
        lines += [f"{r.table_row} & {r.n_features} &",
                  f"  {tex_number(r.acc_mean)} & {tex_number(r.acc_sd)} &",
                  f"  {tex_number(r.auc_mean)} & {tex_number(r.auc_sd)} \\\\"]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    cfg = load_config()
    out = cfg.output_dir(__file__)
    ps = cfg.section("block_complexity")["persite"]
    s9 = cfg.section("appendix_S09_block_complexity_k")
    raw_pca = cfg.section("pca")["raw_benchmark"]
    if ps["classifier"] != "block_complexity.classifier":
        raise ValueError("SI Table S6 uses block_complexity.classifier (200 trees, depth 6, lr 0.1, seed 42)")
    if raw_pca["standardise"] or not raw_pca["per_site"]:
        raise ValueError("SI S9: the raw two-component summary is fitted within each site without standardising")
    digits = int(s9["round_site_metrics"])
    k = read_k(out)

    rows = []
    for site in cfg.sites:
        tab = site_table(cfg, site, k)
        g = tab[evaluation_subset(tab)].reset_index(drop=True)
        if g["y"].nunique() < 2:
            print(f"{site}: skipped (one class only in the evaluation subset)")
            continue
        y = g["y"].to_numpy()
        # PC1 + PC2: unstandardised two-component PCA of the raw indicators, within the site
        pcs = PCA(n_components=int(raw_pca["components"]), random_state=int(s9["feature_basic_pca_seed"])) \
            .fit_transform(g[RAW].to_numpy(float))
        X = {"k": g[["k"]].to_numpy(float), "feature_basic": pcs, "morph25": g[RAW].to_numpy(float)}
        tr, te = train_test_split(np.arange(len(g)), test_size=float(ps["test_size"]),
                                  stratify=y if ps["stratify"] else None,
                                  random_state=int(ps["split_random_state"]))
        line = dict(site=site, n_evaluation=len(g), n_train=len(tr), n_test=len(te))
        for name in FEATURE_SETS:
            clf = fit_classifier(cfg, "block_complexity.classifier", X[name][tr], y[tr])
            pred = clf.predict(X[name][te])
            proba = clf.predict_proba(X[name][te])[:, 1]
            line[f"acc_{name}"] = round(accuracy_score(y[te], pred), digits)
            line[f"auc_{name}"] = round(roc_auc_score(y[te], proba), digits)
        rows.append(line)
        print(f"{site:<24} n={len(g):>7,}  k acc {line['acc_k']:.3f} AUC {line['auc_k']:.3f}  "
              f"raw 25 acc {line['acc_morph25']:.3f} AUC {line['auc_morph25']:.3f}")
    per_site = pd.DataFrame(rows)
    write_table(per_site, out / "k_persite_metrics.csv")

    ddof = int(s9["summary_sd_ddof"])
    summary = []
    for name, (label, n_feat) in FEATURE_SETS.items():
        a, u = per_site[f"acc_{name}"].to_numpy(), per_site[f"auc_{name}"].to_numpy()
        summary.append(dict(feature_set=name, table_row=label, n_features=n_feat, n_sites=len(per_site),
                            acc_mean=round(a.mean(), 3), acc_sd=round(a.std(ddof=ddof), 3),
                            acc_min=a.min(), acc_max=a.max(),
                            auc_mean=round(u.mean(), 3), auc_sd=round(u.std(ddof=ddof), 3),
                            auc_min=u.min(), auc_max=u.max()))
    summary = pd.DataFrame(summary)
    write_table(summary, out / "k_persite_summary.csv")
    with pd.option_context("display.width", 200):
        print(summary.drop(columns="table_row").to_string(index=False))

    write_text(table_tex(summary, cfg), out / "table_bettencourt_persite.tex")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
