"""Pooled cross-site comparison of k with the raw morphological indicators (SI Table S7).

Manuscript items
* SI Table S7: AUC mean and s.d. over five folds of one classifier trained on
  the buildings of all ten sites, for block complexity k alone and the raw 25
  indicators (rows of the table).
* SI S9 'Pooled cross-site protocol'.

Protocol (config.yaml ``block_complexity.pooled``, ``block_complexity.classifier``)
* Buildings: the evaluation subset of every site (valid k, complete Tree-SHAP
  attributions, all 25 raw indicators), stacked site by site in the order
  ``appendix_S09_block_complexity_k.pooled_site_order`` (this order only
  affects which buildings fall into which fold).
* Stratified five-fold cross-validation, shuffled, seed 42.
* XGBoost with 200 trees, max depth 6, learning rate 0.1, random seed 42
  (``block_complexity.classifier``, the classifier of the SI S9 comparison,
  not the main per-site model of Methods 4.4); favela = class 1; intercept =
  favela share of the training rows; AUC per fold.
* Reported: mean and population s.d. (ddof 0) of the five fold AUCs, rounded to
  three decimals.

Inputs
* outputs/appendix/S09_block_complexity_k/block_complexity_k.csv (02)
* products.features_gpkg (main/01_features), products.shap_gpkg (main/02_classification)

Outputs (outputs/appendix/S09_block_complexity_k/)
* k_pooled_auc.csv              feature set, number of features, AUC mean and s.d., n,
                                and the five fold AUCs
* table_bettencourt_pooled.tex  SI Table S7 in LaTeX

Run (from the repository root), after 02_block_complexity_k.py:
    python appendix/S09_block_complexity_k/04_pooled_protocol.py
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold

from favela_xai.config import load_config
from favela_xai.io import write_table, write_text
from favela_xai.model import fit_classifier
from k_common import RAW, evaluation_subset, read_k, site_table, tex_int, tex_number

# feature set -> (row label of SI Table S7, columns)
FEATURE_SETS = {
    "k": ("Block complexity $k$ alone", ["k"]),
    "morph25": ("Raw 25 indicators", RAW),
}


def table_tex(res: pd.DataFrame, cfg) -> str:
    """SI Table S7 in LaTeX (caption values from config.yaml)."""
    m = cfg.section("block_complexity.classifier")
    pooled = cfg.section("block_complexity")["pooled"]
    lines = [
        "% Supplementary Table S7. Generated by appendix/S09_block_complexity_k/04_pooled_protocol.py",
        r"\begin{table}[H]",
        r"\centering",
        rf"\caption{{Pooled cross-site classification AUC ({pooled['n_folds']}-fold stratified",
        rf"  cross-validation, XGBoost with {m['n_estimators']} trees, max depth {m['max_depth']}, learning",
        rf"  rate {tex_number(m['learning_rate'], None)}, random seed {m['random_state']}; n = {tex_int(res['n'].iloc[0])}",
        r"  buildings with valid $k$ and all 25 indicators across the",
        r"  ten sites).}",
        r"\label{tab:bettencourt_pooled}",
        r"\small",
        r"\begin{tabular}{lccc}",
        r"\toprule",
        r"Feature set & $n_{\text{features}}$ & AUC (mean) & AUC (sd) \\",
        r"\midrule",
    ]
    for r in res.itertuples():
        lines += [f"{r.table_row} & {r.n_features} &",
                  f"  {tex_number(r.auc_mean)} & {tex_number(r.auc_sd)} \\\\"]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    cfg = load_config()
    out = cfg.output_dir(__file__)
    pooled = cfg.section("block_complexity")["pooled"]
    s9 = cfg.section("appendix_S09_block_complexity_k")
    if pooled["classifier"] != "block_complexity.classifier":
        raise ValueError("SI Table S7 uses block_complexity.classifier (XGBoost, 200 trees, max depth 6, "
                         "learning rate 0.1, seed 42)")
    if len(cfg.sites) < 2:
        sys.exit("The pooled protocol needs several sites.")
    k = read_k(out)

    # Stack the evaluation subsets site by site (order: pooled_site_order)
    order = [s for s in s9["pooled_site_order"] if s in cfg.sites]
    order += [s for s in cfg.sites if s not in order]
    parts = []
    for site in order:
        tab = site_table(cfg, site, k)
        parts.append(tab[evaluation_subset(tab)])
    data = pd.concat(parts, ignore_index=True)
    y = data["y"].to_numpy()
    print(f"pooled evaluation subset: {len(data):,} buildings ({int(y.sum()):,} favela, "
          f"{int((1 - y).sum()):,} formal settlement)")

    cv = StratifiedKFold(n_splits=int(pooled["n_folds"]), shuffle=bool(pooled["shuffle"]),
                         random_state=int(pooled["random_state"]))
    rows = []
    for name, (label, cols) in FEATURE_SETS.items():
        X = data[cols].to_numpy(float)
        aucs = []
        for tr, te in cv.split(X, y):
            clf = fit_classifier(cfg, "block_complexity.classifier", X[tr], y[tr])
            aucs.append(roc_auc_score(y[te], clf.predict_proba(X[te])[:, 1]))
        aucs = np.asarray(aucs)
        rows.append(dict(feature_set=name, table_row=label, n_features=len(cols),
                         auc_mean=round(aucs.mean(), 3), auc_sd=round(aucs.std(ddof=int(s9["summary_sd_ddof"])), 3),
                         n=len(data), **{f"auc_fold{i + 1}": a for i, a in enumerate(aucs)}))
        print(f"{name:<8} AUC = {aucs.mean():.3f} +- {aucs.std(ddof=int(s9['summary_sd_ddof'])):.3f} (n = {len(data):,})")
    res = pd.DataFrame(rows)
    write_table(res, out / "k_pooled_auc.csv")
    write_text(table_tex(res, cfg), out / "table_bettencourt_pooled.tex")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
