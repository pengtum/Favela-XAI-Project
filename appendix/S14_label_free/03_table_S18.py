"""Step 3 of SI Section S14: Supplementary Table S18 (label-free clustering by weighting scheme).

Manuscript item: SI Table S18, written as table_S18_label_free.tex. Rows 'All
indicators equal', 'Dimensions balanced', 'One component per dimension' (means
over the ten sites of the best result over 2-6 clusters and over k-means and
Ward: best ARI, best balanced accuracy, score AUC, step in SD; pooled profile
correlation r) and the 'Supervised (reference)' row (balanced accuracy 0.904,
AUC 0.969).

Supervised reference: five-fold cross-validation of the SI S12 pipeline
(XGBoost, 100 trees, seed 432); balanced accuracy and AUC are the mean over
sites of the per-site mean over the five folds of the random stratified
five-fold rows of the SI S12 fold table (appendix/S12_spatial_cv,
``products.spatial_cv_folds``), as in SI Fig. S23b.

Inputs: weighting_summary.csv (02_weighting_sensitivity.py);
outputs/appendix/S12_spatial_cv/folds_all.parquet (products.spatial_cv_folds).
Outputs (outputs/appendix/S14_label_free/)
* table_S18_values.csv: the numbers of the table.
* table_S18_label_free.tex: the table float with caption (booktabs).

Run from the repository root:
    python appendix/S14_label_free/03_table_S18.py
"""
from __future__ import annotations

import pandas as pd

import label_free_common as lf
from favela_xai.io import write_table, write_text

CAPTION = (
    r"\textbf{Label-free clustering of the 25 morphological indicators, by weighting scheme.} Means over the ten "
    r"sites of the best result over 2--6 clusters and over $k$-means and Ward clustering. Score AUC, "
    r"orientation-free separation of the continuous two-cluster score; step, inside--outside difference of the "
    r"score in standard deviations; profile $r$, correlation of the normalised boundary profile with that of the "
    r"supervised favela probability. Supervised reference: five-fold cross-validation of the pipeline of "
    r"Section~\ref{sec:spatialcv} (XGBoost, 100 trees, seed 432).")


def num(v: float) -> str:
    """Three decimals (SI style)."""
    return f"{v:.3f}"


def main() -> None:
    cfg = lf.cfg
    summary = pd.read_csv(lf.OUT / "weighting_summary.csv").set_index("weighting").loc[lf.WEIGHTINGS]
    # Supervised reference row: balanced accuracy and AUC both as the mean over the
    # five folds of each site, then over the sites (the random five-fold rows of SI S12)
    sup_bal = lf.supervised_five_fold(cfg.sites, "balanced_accuracy")
    sup_auc = lf.supervised_five_fold(cfg.sites, "auc")

    values = summary[["weighting_name", "best_ARI_mean", "best_bal_acc_mean", "score_AUC_mean", "step_in_sd_mean",
                      "profile_r_pooled"]].reset_index()
    ref = dict(weighting="supervised_reference", weighting_name="Supervised (reference)",
               best_ARI_mean=float("nan"), best_bal_acc_mean=float(sup_bal.mean()),
               score_AUC_mean=float(sup_auc.mean()), step_in_sd_mean=float("nan"), profile_r_pooled=float("nan"))
    values = pd.concat([values, pd.DataFrame([ref])], ignore_index=True)
    write_table(values, lf.OUT / "table_S18_values.csv")

    width = max(len(n) for n in values["weighting_name"])
    body = []
    for _, r in values.iloc[:-1].iterrows():
        body.append(f"{r.weighting_name:<{width}} & {num(r.best_ARI_mean)} & {num(r.best_bal_acc_mean)} & "
                    f"{num(r.score_AUC_mean)} & {num(r.step_in_sd_mean)} & {num(r.profile_r_pooled)} \\\\")
    r = values.iloc[-1]
    reference = (f"{r.weighting_name:<{width}} & --- & {num(r.best_bal_acc_mean)} & {num(r.score_AUC_mean)} "
                 r"& --- & --- \\")
    lines = [
        "% Generated by appendix/S14_label_free/03_table_S18.py (table_S18_values.csv).",
        "% Requires booktabs, float.",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{" + CAPTION + "}",
        r"\label{tab:labelfree}",
        r"\small",
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Weighting & Best ARI & Best bal.\ acc. & Score AUC & Step (SD) & Profile $r$ \\",
        r"\midrule",
        *body,
        r"\midrule",
        reference,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}", ""]
    write_text("\n".join(lines), lf.OUT / "table_S18_label_free.tex")

    pd.set_option("display.width", 200)
    print(values.round(3).to_string(index=False))
    print("Reported in SI Table S18: 0.045/0.628/0.555/0.173/0.879; 0.079/0.646/0.631/0.475/0.942; "
          "0.057/0.633/0.616/0.442/0.952; supervised 0.904 / 0.969.")
    print(f"saved {lf.OUT / 'table_S18_label_free.tex'}")


if __name__ == "__main__":
    main()
