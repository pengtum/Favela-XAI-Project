"""Step 2: Supplementary Table S4, misclassification rate by distance band and side (LaTeX).

Manuscript items
* Supplementary Table S4 (SI S5): buildings, errors, error rate, Wilson and site-bootstrap 95% intervals and
  share of all errors for the bands < 6, 6-30, 30-90 and >= 90 m on the
  favela-labelled side (false negatives), the formal-settlement side (false
  positives) and both sides combined, with the near/far ratio of each side.

Input:  boundary_error_bands.csv (main/02_classification step 04: out-of-fold
        predictions of step 03, stratified five-fold, XGBoost 100 trees, seed 432).
Output: outputs/appendix/S05_boundary_errors/table_R1_exposure_bands.tex (with caption).

Run from the repository root:
    python appendix/S05_boundary_errors/02_table_S4.py
"""
from __future__ import annotations

import pandas as pd

from favela_xai.config import load_config
from favela_xai.io import write_text

import s05_common as C

DOT = "."
CAPTION = (r"\caption{Misclassification rate by signed distance to the 2013 favela boundary, normalised by the "
           r"number of buildings in each distance band. Wilson 95\% CI: score interval for the pooled rate. "
           r"Site-bootstrap 95\% CI: percentile interval over 2{,}000 resamples of the ten sites drawn with "
           r"replacement, pooling buildings within each resample. Share of errors: share of all errors in the ten "
           r"sites. Ratio: error rate within 6\,m divided by the rate at 90\,m or more, with its site-bootstrap "
           r"95\% CI.}")
HEAD = {"inside": r"Inside (favela-labelled side; errors are false negatives)",
        "outside": r"Outside (formal-settlement side; errors are false positives)",
        "both": r"Both sides combined"}


def num(v, d=2):
    return f"{v:.{d}f}".replace(".", DOT)


def pct(v, d=2):
    return num(100 * v, d)


def main() -> None:
    cfg = load_config()
    out = cfg.output_dir(__file__)
    BS = pd.read_csv(C.main02_table(cfg, "bands"))
    labels = C.band_labels(cfg)
    BL = dict(zip(labels, [r"$<$6\,m", r"6--30\,m", r"30--90\,m", r"$\geq$90\,m"]))
    lines = ["% Supplementary Table S4 (SI Section S5). Generated by appendix/S05_boundary_errors/02_table_S4.py",
             "% from boundary_error_bands.csv (main/02_classification). Requires booktabs and float.",
             r"\begin{table}[H]", r"\centering", r"\small", CAPTION, r"\label{tab:exposure_bands}",
             r"\setlength{\tabcolsep}{4.5pt}", r"\begin{tabular}{lrrrccr}", r"\toprule",
             r"Distance & Buildings & Errors & Error & Wilson & Site-bootstrap & Share of \\",
             r"band & & & rate (\%) & 95\% CI & 95\% CI & errors (\%) \\", r"\midrule"]
    for gi, side in enumerate(["inside", "outside", "both"]):
        t = BS[BS.side == side]
        if gi:
            lines.append(r"\addlinespace[3pt]")
        lines.append(r"\multicolumn{7}{l}{\emph{" + HEAD[side] + r"}} \\")
        for _, r in t.iterrows():
            lines.append(f"\\quad {BL[r.band]} & {int(r.n_buildings):,} & {int(r.n_errors):,} & {pct(r.error_rate)} & "
                         f"{pct(r.wilson_lo)}--{pct(r.wilson_hi)} & {pct(r.boot_lo)}--{pct(r.boot_hi)} & "
                         f"{pct(r.share_of_all_errors)} \\\\")
        r = t.iloc[0]
        lines.append(f"\\quad Ratio & & & {num(r.ratio_near_far)} & & {num(r.ratio_boot_lo)}--{num(r.ratio_boot_hi)} & \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    write_text("\n".join(lines) + "\n", out / C.TABLE_S4)
    print("\n".join(lines))
    print(f"written {out / C.TABLE_S4}")


if __name__ == "__main__":
    main()
